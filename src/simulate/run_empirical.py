"""Phase 7: data-based rebalancing simulation. Writes docs/simulation_results.md.

    python src/simulate/run_empirical.py --db dbt/target/valenbisi.duckdb --out docs/simulation_results.md

Steps: (1) estimate demand and station parameters from the dbt tables built on the frozen dataset; (2) read the measured
forecast AUC at 1, 3 and 6 hours; (3) calibrate forecast noise so the simulated forecast has the same ranking skill;
(4) compare policies in the baseline scenario; (5) repeat over a grid of demand scales and rebalancing budgets.
Everything printed is an ASSUMPTION-DRIVEN comparison, not an estimate of real Valenbisi savings.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from simulate import empirical as E  # noqa: E402
from simulate.engine import load_config  # noqa: E402


def md_table(df: pd.DataFrame) -> str:
    def fmt(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else f"{v:.4g}"
        return "" if v is None else str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |\n"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|\n"
    return head + sep + "".join("| " + " | ".join(fmt(v) for v in r) + " |\n" for r in df.itertuples(index=False))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--db", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--config", default=str(Path(__file__).with_name("config.toml")))
    ap.add_argument("--docs", default="docs", type=Path, help="folder holding the forecast_results*.md files")
    ap.add_argument("--quick", action="store_true", help="few replications, for a smoke test")
    a = ap.parse_args(argv)

    cfg = load_config(a.config)
    ec = cfg["empirical"]
    reps = 6 if a.quick else ec["n_replications"]
    grid_reps = 4 if a.quick else ec["grid_replications"]
    cal_reps = 4 if a.quick else ec["calibration_replications"]
    seed = ec["seed"]
    est_dir = Path(ec["estimate_dir"])

    p = E.estimate(a.db)
    E.save_params(p, est_dir)
    targets = E.measured_aucs(a.docs)
    calib = E.calibrate_noise(p, cfg, targets, reps=cal_reps, seed=seed)
    specs = E.policy_specs(calib)
    rb = cfg["rebalancing"]
    base_budget = rb["n_trucks"] * rb["transfers_per_truck_per_round"]

    lines = ["# Simulation results (auto-generated)", "",
             "**ASSUMPTION-DRIVEN comparison of rebalancing policies on a replica of the real network. Not an estimate of real savings.** "
             "Generated by `src/simulate/run_empirical.py`. Interpretation: `docs/simulation_findings.md`.", ""]

    summ = pd.DataFrame([{"item": k, "value": v} for k, v in p.summary.items()])
    lines += ["## E1. What was estimated from the data", "",
              "Counted pickups and returns are lower bounds on true trips. Jumps of 8 bikes or more in one step are treated as truck moves "
              "and left out of the rates; their daily count is shown for context on the size of real rebalancing.", "", md_table(summ)]

    cal_rows = [{"horizon_h": H, "measured_auc": c["target_auc"], "noise_sd_bikes": c["noise_sd_bikes"], "auc_with_no_noise": c["auc_no_noise"],
                 "auc_reactive_current_count_only": c["auc_reactive"], "stockout_event_rate": c["event_rate"], "note": c["note"]} for H, c in calib.items()]
    lines += ["## E2. Forecast noise matched to the measured forecast accuracy", "",
              "In the simulator the forecast predicts net bike outflow over the next H hours with added noise (sd in bikes). The noise is chosen so "
              "that 'projected level' ranks stations by risk of hitting zero within H hours with the same AUC the real gradient-boosted model "
              "achieved in the backtest (docs/forecast_results*.md). Matching is by ranking skill only; the real forecast and the simulated one "
              "predict different quantities, so treat this as a rough translation.", "", md_table(pd.DataFrame(cal_rows).round(4))]

    val = E.validation(p, cfg, a.db, reps=4 if a.quick else 8, seed=seed + 500, demand_scale=ec["baseline_demand_scale"])
    lines += ["## E2b. Does the simulated network resemble the real one? (validation)", "",
              "Real = the frozen dataset's headline shares (which include whatever rebalancing the operator really does). Simulated = no rebalancing at all, "
              "end-of-hour states averaged over simulated days. **The simulation understates how often stations are empty**, so absolute lost-pickup "
              "numbers below should not be read as real; only relative comparisons between policies are meaningful, and even those are assumption-bound.", "",
              md_table(val["overall"].round(4)), "### Do simulated stations rank like real ones?", "", md_table(val["ranks"].round(3)),
              "### Time-of-day pattern", "", md_table(val["blocks"].round(4)), md_table(val["shape"].round(3))]

    base_scale = ec["baseline_demand_scale"]
    df = E.run_scenario(p, cfg, specs, reps, seed, base_scale)
    s1 = E.summarize(df, "none")
    comp = []
    for name in [s["name"] for s in specs if s["name"].startswith(("forecast", "oracle", "static"))]:
        m, lo, hi = E.paired_difference(df, name, "reactive")
        comp.append({"policy": name, "extra_lost_pickups_avoided_per_day_vs_reactive": m, "lo95": lo, "hi95": hi})
    lines += [f"## E3. Baseline scenario (demand scale {base_scale}, {base_budget} transfers per round, {reps} replications, "
              f"{cfg['system']['n_days']} simulated days each)", "",
              "Lost pickups = riders who wanted a bike at an empty station. 'avoided' = reduction versus no rebalancing, paired by replication; "
              "the interval is a 95% confidence interval for the AVERAGE over replications; sd_across_replications shows how much a single "
              "5-day run varies.", "", md_table(s1.round(4)),
              "### E3b. Does forecasting add anything beyond reacting to current counts?", "",
              "Positive = fewer lost pickups per day than the reactive policy. Interval = 95% confidence interval for the average.", "",
              md_table(pd.DataFrame(comp).round(4))]

    grid_specs = [s for s in specs if s["name"] in ("none", "reactive", "forecast_3h", "oracle_3h")]
    grid_rows = []
    for scale in ec["demand_scales"]:
        for budget in ec["transfers_per_round"]:
            g = E.run_scenario(p, cfg, grid_specs, grid_reps, seed + 1000, scale, budget)
            lp = g.groupby("name")["lost_pickups_per_day"].mean()
            fr = E.paired_difference(g, "forecast_3h", "reactive")
            orr = E.paired_difference(g, "oracle_3h", "reactive")
            rn = E.paired_difference(g, "reactive", "none")
            grid_rows.append({"demand_scale": scale, "transfers_per_round": budget, "lost_per_day_none": lp["none"],
                              "lost_per_day_reactive": lp["reactive"], "lost_per_day_forecast_3h": lp["forecast_3h"], "lost_per_day_oracle_3h": lp["oracle_3h"],
                              "reactive_avoids_vs_none": rn[0], "forecast_3h_beats_reactive_by": fr[0], "fc_lo95": fr[1], "fc_hi95": fr[2],
                              "oracle_beats_reactive_by": orr[0], "or_lo95": orr[1], "or_hi95": orr[2]})
    grid = pd.DataFrame(grid_rows)
    lines += [f"## E4. Sensitivity to demand scale and rebalancing budget ({grid_reps} replications per cell)", "",
              "Demand scale 1.0 = counted pickups; higher values assume true demand is larger than what bike-count changes reveal. "
              "'beats reactive by' is lost pickups per day avoided relative to the reactive policy, with 95% confidence intervals for the average.", "", md_table(grid.round(3))]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

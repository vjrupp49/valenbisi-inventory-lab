"""Descriptive service-level analysis (Phase 4): how often stations are empty or full, when, and where.

    python src/analysis/service_level.py --db dbt/target/valenbisi.duckdb --out docs/service_level_results.md \
        --cache reports/_cache

Reads the dbt tables (built from the frozen dataset) and writes (1) a markdown file of tables and (2) CSVs that the
R plotting script uses. Every number in docs/service_level_findings.md comes from this output.

Conventions
  * Only COMPLETE Madrid-local days are used (a day needs at least MIN_SNAPSHOTS_PER_DAY snapshots), so partial first
    and last days cannot distort hour-of-day patterns.
  * "Headline" rates use the eligible populations defined in dbt/models/marts/fct_station_snapshot.sql.
  * Stockout rates are LOWER BOUNDS: stockouts shorter than the 10-minute snapshot spacing can be missed.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb
import pandas as pd

MIN_SNAPSHOTS_PER_DAY = 138       # about 96 % of the nominal 144
MIN_CELL_ROWS = 80                # a station-hour cell needs this many eligible snapshots to be shown (about 13 days)
CHRONIC = 0.5                     # headline stockout (or blockout) rate at or above this = "chronic"
PROBLEM_STATION = 0.25            # overall rate at or above this = "problem station" (still counted in the chronic table)


def md_table(df: pd.DataFrame) -> str:
    if df.empty:
        return "_(no rows)_\n"

    def fmt(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else f"{v:.4g}"
        return "" if v is None or (not isinstance(v, str) and pd.isna(v)) else str(v)

    head = "| " + " | ".join(map(str, df.columns)) + " |\n"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|\n"
    body = "".join("| " + " | ".join(fmt(v) for v in row) + " |\n" for row in df.itertuples(index=False))
    return head + sep + body


def run(db: Path, out: Path, cache: Path) -> dict[str, pd.DataFrame]:
    con = duckdb.connect(str(db), read_only=True)
    con.execute("SET TimeZone='UTC'")
    # Complete local days, with a day-type label.
    con.execute(
        f"""
        CREATE TEMP TABLE days AS
        SELECT local_date, count(DISTINCT snapshot_ts) AS snapshots,
               CASE WHEN bool_or(is_holiday) THEN 'holiday'
                    WHEN isodow(local_date) >= 6 THEN 'weekend' ELSE 'weekday' END AS day_type
        FROM fct_station_snapshot GROUP BY 1 HAVING count(DISTINCT snapshot_ts) >= {MIN_SNAPSHOTS_PER_DAY}
        """
    )
    con.execute("CREATE TEMP VIEW f AS SELECT s.*, d.day_type FROM fct_station_snapshot s JOIN days d USING (local_date) WHERE s.is_installed")
    res: dict[str, pd.DataFrame] = {}
    lines = ["# Service level results (auto-generated)", "",
             "Generated by `src/analysis/service_level.py`. Do not edit by hand. Interpretation: `docs/service_level_findings.md`.", ""]

    def add(cid: str, title: str, sql: str, note: str = "") -> pd.DataFrame:
        df = con.execute(sql).df()
        res[cid] = df
        lines.extend([f"### {cid}. {title}", ""] + ([note, ""] if note else []) + [md_table(df)])
        return df

    lines += ["## Coverage", ""]
    add("S1", "Days used (complete Madrid-local days)",
        "SELECT day_type, count(*) AS days, min(local_date) AS first_day, max(local_date) AS last_day, min(snapshots) AS min_snapshots, "
        "max(snapshots) AS max_snapshots FROM days GROUP BY 1 ORDER BY 1")
    add("S2", "Rows and exclusions (installed stations, complete days)",
        "SELECT count(*) AS installed_rows, count(*) FILTER (WHERE is_not_renting) AS not_renting_rows, "
        "count(*) FILTER (WHERE is_renting AND is_stuck_excluded) AS renting_and_stuck_excluded, "
        "count(*) FILTER (WHERE is_stockout_eligible) AS stockout_eligible_rows, "
        "count(*) FILTER (WHERE is_blockout_eligible) AS blockout_eligible_rows, "
        "round(1 - count(*) FILTER (WHERE is_stockout_eligible) * 1.0 / count(*) FILTER (WHERE is_renting), 4) AS share_of_renting_rows_excluded "
        "FROM f")

    lines += ["## City-wide rates", ""]
    add("S3", "Stockout and blockout rate, three versions (share of eligible station-snapshots)",
        "SELECT round(avg(is_stockout::int) FILTER (WHERE is_renting), 4) AS stockout_raw, "
        "round(avg(is_stockout::int) FILTER (WHERE is_stockout_eligible), 4) AS stockout_headline, "
        "round(avg(is_stockout::int) FILTER (WHERE is_renting AND NOT is_stuck), 4) AS stockout_strict, "
        "round(avg(is_blockout::int) FILTER (WHERE is_returning), 4) AS blockout_raw, "
        "round(avg(is_blockout::int) FILTER (WHERE is_blockout_eligible), 4) AS blockout_headline, "
        "round(avg(is_blockout::int) FILTER (WHERE is_returning AND NOT is_stuck), 4) AS blockout_strict FROM f")
    add("S4", "Sensitivity of the headline stockout rate to the stuck-exclusion threshold",
        "SELECT t AS exclude_flat_at_least_hours, round(avg(is_stockout::int) FILTER (WHERE is_renting AND flat_hours < t), 4) AS stockout_rate, "
        "count(*) FILTER (WHERE is_renting AND flat_hours < t) AS eligible_rows "
        "FROM f, (VALUES (3), (6), (12), (24), (1000000)) v(t) GROUP BY 1 ORDER BY 1",
        "The last row (1,000,000 h) means no exclusion at all.")

    lines += ["## By hour of day (Madrid time)", ""]
    hourly_day = con.execute(
        "SELECT day_type, local_date, hour_of_day, avg(is_stockout::int) FILTER (WHERE is_stockout_eligible) AS stockout_rate, "
        "avg(is_blockout::int) FILTER (WHERE is_blockout_eligible) AS blockout_rate, "
        "count(*) FILTER (WHERE is_stockout_eligible) AS n FROM f GROUP BY ALL"
    ).df()
    cache.mkdir(parents=True, exist_ok=True)
    hourly_day.to_csv(cache / "hourly_by_day.csv", index=False)
    g = hourly_day.groupby(["day_type", "hour_of_day"])
    hourly = g.agg(days=("local_date", "nunique"), stockout_median=("stockout_rate", "median"),
                   stockout_min=("stockout_rate", "min"), stockout_max=("stockout_rate", "max"),
                   blockout_median=("blockout_rate", "median"), blockout_min=("blockout_rate", "min"),
                   blockout_max=("blockout_rate", "max")).reset_index().round(4)
    res["S5"] = hourly
    hourly.to_csv(cache / "hourly_summary.csv", index=False)
    lines += ["### S5. City-wide headline rate by Madrid hour: median, minimum and maximum across days of the same type", "",
              "Each day contributes one city-wide rate per hour. Min/max show day-to-day spread; with so few days they are the honest uncertainty.", "",
              md_table(hourly[hourly["day_type"].isin(["weekday", "weekend"])].pivot(index="hour_of_day", columns="day_type",
                       values=["stockout_median", "blockout_median"]).round(4).reset_index().pipe(
                           lambda d: d.set_axis([f"{a}_{b}" if b else a for a, b in d.columns], axis=1)))]

    lines += ["## By station", ""]
    st = con.execute(
        "SELECT station_id, count(*) AS installed_rows, count(*) FILTER (WHERE is_stockout_eligible) AS n_stockout_eligible, "
        "count(*) FILTER (WHERE is_blockout_eligible) AS n_blockout_eligible, "
        "count(*) FILTER (WHERE is_stuck_excluded) AS n_stuck_excluded, count(*) FILTER (WHERE is_not_renting) AS n_not_renting, "
        "avg(is_stockout::int) FILTER (WHERE is_stockout_eligible) AS stockout_rate, "
        "avg(is_stockout::int) FILTER (WHERE is_renting) AS stockout_raw, "
        "avg(is_blockout::int) FILTER (WHERE is_blockout_eligible) AS blockout_rate, "
        "avg(is_blockout::int) FILTER (WHERE is_returning) AS blockout_raw, max(capacity) AS capacity, "
        "avg(bikes) AS mean_bikes FROM f GROUP BY 1"
    ).df()
    st = st[st["n_stockout_eligible"] > 0].copy()
    st.round(4).to_csv(cache / "station_summary.csv", index=False)
    q = st[["stockout_rate", "blockout_rate"]].quantile([0.1, 0.25, 0.5, 0.75, 0.9]).round(4).reset_index().rename(columns={"index": "quantile"})
    res["S6"] = q
    lines += ["### S6. Spread of station-level headline rates across stations", "", md_table(q)]
    counts = pd.DataFrame([{
        "stations_with_data": len(st),
        f"stockout_rate_ge_{CHRONIC}": int((st["stockout_rate"] >= CHRONIC).sum()),
        f"stockout_rate_ge_{PROBLEM_STATION}": int((st["stockout_rate"] >= PROBLEM_STATION).sum()),
        f"blockout_rate_ge_{CHRONIC}": int((st["blockout_rate"] >= CHRONIC).sum()),
        f"blockout_rate_ge_{PROBLEM_STATION}": int((st["blockout_rate"] >= PROBLEM_STATION).sum()),
        "stockout_rate_zero": int((st["stockout_rate"] == 0).sum()),
    }])
    res["S7"] = counts
    lines += ["### S7. Counts of problem stations", "", md_table(counts)]
    top = st.sort_values("stockout_rate", ascending=False).head(15)[
        ["station_id", "capacity", "n_stockout_eligible", "n_stuck_excluded", "stockout_rate", "stockout_raw", "blockout_rate", "mean_bikes"]].round(4)
    res["S8"] = top
    lines += ["### S8. 15 stations with the highest headline stockout rate", "", md_table(top)]
    topb = st.sort_values("blockout_rate", ascending=False).head(15)[
        ["station_id", "capacity", "n_blockout_eligible", "n_stuck_excluded", "blockout_rate", "blockout_raw", "stockout_rate", "mean_bikes"]].round(4)
    res["S9"] = topb
    lines += ["### S9. 15 stations with the highest headline blockout rate", "", md_table(topb)]

    cells = con.execute(
        f"SELECT station_id, hour_of_day, count(*) FILTER (WHERE is_stockout_eligible) AS n, "
        f"avg(is_stockout::int) FILTER (WHERE is_stockout_eligible) AS stockout_rate, "
        f"avg(is_blockout::int) FILTER (WHERE is_blockout_eligible) AS blockout_rate FROM f GROUP BY 1, 2 "
        f"HAVING count(*) FILTER (WHERE is_stockout_eligible) >= {MIN_CELL_ROWS}"
    ).df()
    cells.round(4).to_csv(cache / "station_hour_cells.csv", index=False)
    peak = cells.merge(st[["station_id", "stockout_rate"]].rename(columns={"stockout_rate": "overall"}), on="station_id")
    peak = peak[(peak["overall"] < PROBLEM_STATION) & (peak["stockout_rate"] >= CHRONIC)]
    peak_st = peak.groupby("station_id").agg(hours_with_stockout_rate_ge_half=("hour_of_day", "count"),
                                              worst_hour=("hour_of_day", lambda s: int(peak.loc[s.index].sort_values("stockout_rate").iloc[-1]["hour_of_day"])),
                                              worst_rate=("stockout_rate", "max"), overall_rate=("overall", "first")).reset_index()
    peak_st = peak_st.sort_values("worst_rate", ascending=False).round(4)
    res["S10"] = peak_st.head(15)
    lines += ["### S10. 'Peak-hour' stations: overall rate under 25 % but at least 50 % in some hour (cells with >= "
              f"{MIN_CELL_ROWS} eligible snapshots); count = {len(peak_st)}", "", md_table(peak_st.head(15))]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    con.close()
    return res


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--db", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--cache", type=Path, default=Path("reports/_cache"))
    a = ap.parse_args()
    run(a.db, a.out, a.cache)
    print(f"wrote {a.out}")

"""Phase 5: how stable are the ABC / XYZ station segments?

    python src/analysis/segmentation_stability.py --db dbt/target/valenbisi.duckdb --out docs/segmentation_results.md

Segments (same logic as dbt/models/marts/seg_station_abc_xyz.sql, re-implemented here so it can be re-run on subsets of days):
  ABC: stations ranked by mean daily inferred activity; A = stations whose running total BEFORE them is below the
       A cutoff (default 80 %) of total activity, B = below 95 %, C = the rest.
  XYZ: coefficient of variation (sd / mean) of daily activity; X <= 0.5, Y <= 1.0, Z above; mean 0 -> 'n/a'.
Stability tests: (1) first half vs second half of the days, (2) alternating days, (3) changing the cutoffs,
(4) bootstrap over days. All numbers are written to the output markdown.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd
from sklearn.metrics import cohen_kappa_score

A_CUT, B_CUT, X_MAX, Y_MAX = 0.80, 0.95, 0.5, 1.0
MIN_SNAPSHOTS_PER_DAY = 24     # same as dbt var min_snapshots_per_day
N_BOOT = 500
SEED = 42


def classify(daily: pd.DataFrame, a_cut=A_CUT, b_cut=B_CUT, x_max=X_MAX, y_max=Y_MAX) -> pd.DataFrame:
    """daily: columns station_id, local_date, daily_activity. Returns one row per station with abc_class / xyz_class."""
    g = daily.groupby("station_id")["daily_activity"]
    st = pd.DataFrame({"n_days": g.size(), "mean": g.mean(), "sd": g.std(ddof=1)}).reset_index()
    st = st.sort_values(["mean", "station_id"], ascending=[False, True]).reset_index(drop=True)
    total = st["mean"].sum()
    cum_before = st["mean"].cumsum() - st["mean"]
    share = cum_before / total if total > 0 else cum_before * 0
    st["abc_class"] = np.where(share < a_cut, "A", np.where(share < b_cut, "B", "C"))
    if total == 0:
        st["abc_class"] = "C"
    cv = st["sd"] / st["mean"].replace(0, np.nan)
    st["cv"] = cv
    st["xyz_class"] = np.select([st["mean"].eq(0) | st["sd"].isna(), cv <= x_max, cv <= y_max], ["n/a", "X", "Y"], "Z")
    return st


def agreement(a: pd.Series, b: pd.Series) -> dict:
    idx = a.index.intersection(b.index)
    a, b = a.loc[idx], b.loc[idx]
    return {"stations": len(idx), "same_class_share": round(float((a == b).mean()), 4),
            "cohens_kappa": round(float(cohen_kappa_score(a, b)), 4)}


def md_table(df: pd.DataFrame) -> str:
    def fmt(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else f"{v:.4g}"
        return "" if v is None else str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |\n"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|\n"
    return head + sep + "".join("| " + " | ".join(fmt(v) for v in r) + " |\n" for r in df.itertuples(index=False))


def run(db: Path, out: Path) -> dict:
    con = duckdb.connect(str(db), read_only=True)
    con.execute("SET TimeZone='UTC'")
    daily = con.execute(
        f"SELECT station_id, local_date, sum(activity) AS daily_activity FROM fct_station_snapshot WHERE is_service_eligible "
        f"GROUP BY 1, 2 HAVING count(*) >= {MIN_SNAPSHOTS_PER_DAY}"
    ).df()
    sql_seg = con.execute("SELECT station_id, abc_class, xyz_class FROM seg_station_abc_xyz WHERE abc_class <> 'n/a'").df().set_index("station_id")
    so = con.execute(
        "SELECT station_id, avg(is_stockout::int) FILTER (WHERE is_stockout_eligible) AS stockout_rate, "
        "avg(is_blockout::int) FILTER (WHERE is_blockout_eligible) AS blockout_rate FROM fct_station_snapshot "
        "WHERE is_service_eligible GROUP BY 1"
    ).df().set_index("station_id")
    con.close()

    res: dict = {}
    lines = ["# Segmentation stability results (auto-generated)", "",
             "Generated by `src/analysis/segmentation_stability.py`. Interpretation: `docs/segmentation_findings.md`.", ""]
    days = sorted(daily["local_date"].unique())
    full = classify(daily).set_index("station_id")
    # sanity: the Python re-implementation must reproduce the dbt model
    cmp = full.join(sql_seg.add_suffix("_sql"), how="inner")
    res["matches_sql"] = bool(((cmp["abc_class"] == cmp["abc_class_sql"]) & (cmp["xyz_class"] == cmp["xyz_class_sql"])).all())
    lines += ["## Basics", "", f"- Days used: {len(days)} ({days[0]} to {days[-1]}), stations classified: {len(full)}.",
              f"- Python re-implementation matches the dbt model for every station: **{res['matches_sql']}**.", ""]
    counts = pd.crosstab(full["abc_class"], full["xyz_class"]).reset_index()
    res["counts"] = counts
    lines += ["### P1. Stations per ABC x XYZ cell (all days)", "", md_table(counts)]
    abc_stats = full.groupby("abc_class").agg(stations=("mean", "size"), mean_daily_activity=("mean", "mean"),
                                              share_of_total=("mean", lambda s: s.sum() / full["mean"].sum())).reset_index()
    res["abc_stats"] = abc_stats
    lines += ["### P2. ABC classes: number of stations and share of all inferred activity", "", md_table(abc_stats.round(4))]

    def split_rows(name, d1, d2):
        s1 = classify(daily[daily["local_date"].isin(d1)]).set_index("station_id")
        s2 = classify(daily[daily["local_date"].isin(d2)]).set_index("station_id")
        rho = s1["mean"].corr(s2["mean"].reindex(s1.index), method="spearman")
        return {"split": name, "days_a": len(d1), "days_b": len(d2),
                **{f"abc_{k}": v for k, v in agreement(s1["abc_class"], s2["abc_class"]).items() if k != "stations"},
                **{f"xyz_{k}": v for k, v in agreement(s1["xyz_class"], s2["xyz_class"]).items() if k != "stations"},
                "activity_rank_spearman": round(float(rho), 4), "stations": len(s1.index.intersection(s2.index))}

    half = len(days) // 2
    splits = pd.DataFrame([
        split_rows("first half vs second half", days[:half], days[half:]),
        split_rows("odd days vs even days", days[0::2], days[1::2]),
    ])
    res["splits"] = splits
    lines += ["### P3. Agreement between segments computed on different halves of the days", "",
              "Same-class share = fraction of stations given the same class by both halves. Kappa corrects for chance (1 = perfect, 0 = chance).",
              "", md_table(splits)]

    rows = []
    variants = {"baseline (80/95, CV 0.5/1.0)": {}, "ABC cutoffs 75/90": dict(a_cut=0.75, b_cut=0.90), "ABC cutoffs 85/97": dict(a_cut=0.85, b_cut=0.97),
                "XYZ cutoffs 0.4/0.8": dict(x_max=0.4, y_max=0.8), "XYZ cutoffs 0.6/1.2": dict(x_max=0.6, y_max=1.2)}
    for name, kw in variants.items():
        v = classify(daily, **kw).set_index("station_id")
        rows.append({"variant": name, "abc_changed_share": round(float((v["abc_class"] != full["abc_class"]).mean()), 4),
                     "xyz_changed_share": round(float((v["xyz_class"] != full["xyz_class"]).mean()), 4)})
    thr = pd.DataFrame(rows)
    res["thresholds"] = thr
    lines += ["### P4. Share of stations whose class changes when the cutoffs are moved", "", md_table(thr)]

    rng = np.random.default_rng(SEED)
    wide = daily.pivot(index="local_date", columns="station_id", values="daily_activity")
    cls = {"abc": [], "xyz": []}
    for _ in range(N_BOOT):
        pick = rng.choice(len(wide), size=len(wide), replace=True)
        long = wide.iloc[pick].reset_index(drop=True).stack().rename("daily_activity").reset_index()
        long.columns = ["local_date", "station_id", "daily_activity"]
        b = classify(long).set_index("station_id")
        cls["abc"].append(b["abc_class"])
        cls["xyz"].append(b["xyz_class"])
    boot = {}
    for k in ("abc", "xyz"):
        m = pd.concat(cls[k], axis=1)
        modal_share = m.apply(lambda r: r.value_counts(normalize=True).iloc[0], axis=1)
        boot[k] = {"stations": len(m), "median_modal_share": round(float(modal_share.median()), 4),
                   "share_stations_ge_90pct": round(float((modal_share >= 0.9).mean()), 4),
                   "share_stations_ge_70pct": round(float((modal_share >= 0.7).mean()), 4),
                   "agrees_with_full_data_modal": round(float((m.apply(lambda r: r.value_counts().index[0], axis=1) == full[f"{k}_class"].reindex(m.index)).mean()), 4)}
    bt = pd.DataFrame(boot).T.reset_index().rename(columns={"index": "dimension"})
    res["bootstrap"] = bt
    lines += [f"### P5. Bootstrap over days ({N_BOOT} resamples of the {len(days)} days)", "",
              "For each station: how often does it land in its most common class? 1.0 = always the same class.", "", md_table(bt)]

    seg = full[["abc_class", "xyz_class"]].join(so)
    by = seg.groupby("abc_class").agg(stations=("stockout_rate", "size"), median_stockout=("stockout_rate", "median"),
                                      median_blockout=("blockout_rate", "median")).reset_index()
    res["by_abc"] = by
    lines += ["### P6. Descriptive link between activity class and service level (headline rates)", "", md_table(by.round(4))]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return res


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--db", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    run(a.db, a.out)
    print(f"wrote {a.out}")

"""Honest evaluation of the stockout forecasts: rolling-origin backtest, baselines, confidence intervals.

    python src/forecast/evaluate.py --db dbt/target/valenbisi.duckdb --out docs/forecast_results.md

Question answered: "will this station have a stockout (eligible rows only) in the NEXT clock hour (UTC), given what we
knew at the start of the current hour?" Each test day is predicted from a model fitted ONLY on earlier hours (training
labels must end before the test day). Uncertainty comes from resampling whole test days (a block bootstrap), because
hours within a day are not independent.

Guard: refuses real-data results below MIN_REAL_DAYS days (project rule); use --synthetic for development.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from forecast.backtest import rolling_origin  # noqa: E402
from forecast.features import FEATURES, TARGET, build_dataset, load_hourly, n_days  # noqa: E402
from forecast.metrics import auc, brier, calibration_table, expected_calibration_error, log_loss  # noqa: E402
from forecast.models import all_models  # noqa: E402

MIN_REAL_DAYS = 14
REF_MODELS = ["persistence", "station_mean", "station_state", "hour_of_week"]
BLOCKS = {"night 00-05": (0, 5), "morning 06-11": (6, 11), "afternoon 12-17": (12, 17), "evening 18-23": (18, 23)}


def md_table(df: pd.DataFrame) -> str:
    def fmt(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else f"{v:.4g}"
        return "" if v is None else str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |\n"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|\n"
    return head + sep + "".join("| " + " | ".join(fmt(v) for v in r) + " |\n" for r in df.itertuples(index=False))


def day_block_bootstrap(preds: pd.DataFrame, n_boot: int, seed: int = 0) -> dict:
    """Per-model Brier and Brier skill (vs each reference model) with 95 % intervals from resampling test days."""
    preds = preds.assign(se=(preds["p"] - preds[TARGET]) ** 2)
    per_day = preds.groupby(["model", "fold_date"]).agg(sse=("se", "sum"), n=("se", "size")).reset_index()
    sse = per_day.pivot(index="fold_date", columns="model", values="sse")
    cnt = per_day.pivot(index="fold_date", columns="model", values="n")
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(sse), size=(n_boot, len(sse)))
    s = sse.to_numpy()
    c = cnt.to_numpy()
    cols = list(sse.columns)
    brier_b = np.stack([s[i].sum(axis=0) / c[i].sum(axis=0) for i in idx])          # (n_boot, n_models)
    point = s.sum(axis=0) / c.sum(axis=0)
    out = {"brier": {}, "skill": {}}
    for j, m in enumerate(cols):
        out["brier"][m] = (point[j], *np.percentile(brier_b[:, j], [2.5, 97.5]))
        out["skill"][m] = {}
        for r in REF_MODELS:
            if r in cols and r != m:
                k = cols.index(r)
                sk = 1 - brier_b[:, j] / brier_b[:, k]
                out["skill"][m][r] = (1 - point[j] / point[k], *np.percentile(sk, [2.5, 97.5]))
    return out


def evaluate(db: str, out: Path, horizon: int = 1, min_train_days: int = 7, n_boot: int = 1000, synthetic: bool = False) -> dict:
    hourly = load_hourly(db)
    days = n_days(hourly)
    if not synthetic and days < MIN_REAL_DAYS:
        print(f"Only {days} distinct day(s) of real data; need {MIN_REAL_DAYS}. Not reporting results (by design).")
        return {}
    ds = build_dataset(hourly, horizon)
    preds = rolling_origin(ds, horizon, min_train_days)
    if preds.empty:
        print("Not enough days for a backtest fold.")
        return {}
    label = "SYNTHETIC DATA - NOT A REAL RESULT" if synthetic else "REAL DATA (frozen dataset)"
    res: dict = {"label": label}
    lines = ["# Forecast results (auto-generated)", "", f"**{label}.** Generated by `src/forecast/evaluate.py`. "
             "Interpretation: `docs/forecast_findings.md`.", "",
             f"- Target: any stockout in the next clock hour (UTC), horizon {horizon} h; eligible rows only (see `analysis_charter.md`).",
             f"- Dataset: {len(ds):,} station-hours, {ds['station_id'].nunique()} stations, {days} distinct UTC days; features: {', '.join(FEATURES)}.",
             f"- Rolling origin: expanding window, first test day after {min_train_days} training days, "
             f"{preds['fold_date'].nunique()} test days, {len(preds) // preds['model'].nunique():,} predictions per model.", ""]

    boot = day_block_bootstrap(preds, n_boot)
    rows = []
    for m, g in preds.groupby("model"):
        b = boot["brier"][m]
        row = {"model": m, "base_rate": g[TARGET].mean(), "brier": b[0], "brier_lo": b[1], "brier_hi": b[2],
               "auc": auc(g[TARGET], g["p"]), "log_loss": log_loss(g[TARGET], g["p"]), "ece": expected_calibration_error(g[TARGET], g["p"])}
        rows.append(row)
    overall = pd.DataFrame(rows).sort_values("brier").reset_index(drop=True)
    res["overall"] = overall
    lines += ["## F1. Overall scores (lower Brier and log-loss are better; higher AUC is better)", "",
              "95 % interval for Brier from resampling test days (day-block bootstrap).", "", md_table(overall.round(4))]

    sk_rows = []
    for m in boot["skill"]:
        for r, v in boot["skill"][m].items():
            sk_rows.append({"model": m, "versus": r, "brier_skill": v[0], "lo95": v[1], "hi95": v[2],
                            "interval_excludes_zero": bool(v[1] > 0 or v[2] < 0)})
    skill = pd.DataFrame(sk_rows)
    res["skill"] = skill
    lines += ["## F2. Brier skill: 1 - Brier(model) / Brier(reference)", "",
              "Positive = better than the reference. If the 95 % interval includes zero we cannot claim a difference.", "",
              md_table(skill[skill["model"].isin(["gbm", "hour_of_week", "station_state"])].round(4))]

    per_day = preds.assign(se=(preds["p"] - preds[TARGET]) ** 2).groupby(["fold_date", "model"])["se"].mean().unstack().reset_index()
    per_day["fold_date"] = per_day["fold_date"].astype(str).str[:10]
    res["per_day"] = per_day
    lines += ["## F3. Brier by test day", "", md_table(per_day.round(4))]

    meta = ds[["station_id", "hour_utc", "hour_of_day"]]
    pm = preds.merge(meta, on=["station_id", "hour_utc"], how="left")
    brow = []
    for name, (lo, hi) in BLOCKS.items():
        sub = pm[(pm["hour_of_day"] >= lo) & (pm["hour_of_day"] <= hi)]
        r = {"madrid_hours": name, "base_rate": sub[TARGET].mean()}
        for m, g in sub.groupby("model"):
            r[m] = brier(g[TARGET], g["p"])
        brow.append(r)
    blocks = pd.DataFrame(brow)
    res["blocks"] = blocks
    lines += ["## F4. Brier by time of day (Madrid hours)", "", md_table(blocks.round(4))]

    for m in ("gbm", "station_state"):
        g = preds[preds["model"] == m]
        cal = calibration_table(g[TARGET], g["p"])
        res[f"cal_{m}"] = cal
        lines += [f"## F5. Calibration: {m}", "", "mean_pred should be close to obs_rate in every bin.", "", md_table(cal.round(4))]

    # which features matter (permutation importance on the last test day's fold)
    try:
        from sklearn.inspection import permutation_importance

        last = sorted(ds["date"].unique())[-1]
        tr = ds[ds["hour_utc"] + pd.Timedelta(hours=horizon) < pd.Timestamp(last)]
        te = ds[ds["date"] == last]
        gb = [m for m in all_models(0) if m.name == "gbm"][0].fit(tr)
        if gb.constant_ is None:
            X = te[FEATURES].astype(float)
            pi = permutation_importance(gb.model_, X, te[TARGET], scoring="neg_brier_score", n_repeats=5, random_state=0)
            imp = pd.DataFrame({"feature": FEATURES, "importance_brier_increase": pi.importances_mean}).sort_values("importance_brier_increase", ascending=False)
            res["importance"] = imp
            lines += ["## F6. Feature importance (how much Brier worsens when a feature is shuffled; last test day only)", "", md_table(imp.round(5))]

            # Placebo: give each test row the features of a RANDOM OTHER station in the same hour. If the model were
            # cheating from something other than the station's own recent state, scores would not collapse.
            rng = np.random.default_rng(0)
            sh = te.copy()
            for _, idx in sh.groupby("hour_utc").groups.items():
                perm = rng.permutation(len(idx))
                sh.loc[idx, FEATURES] = te.loc[idx, FEATURES].to_numpy()[perm]
            p_real = gb.predict_proba(te)
            p_plac = gb.predict_proba(sh)
            plac = pd.DataFrame([
                {"check": "real features", "brier": brier(te[TARGET], p_real), "auc": auc(te[TARGET], p_real)},
                {"check": "features swapped between stations in the same hour", "brier": brier(te[TARGET], p_plac), "auc": auc(te[TARGET], p_plac)},
                {"check": "constant base rate (reference)", "brier": brier(te[TARGET], np.full(len(te), tr[TARGET].mean())), "auc": 0.5},
            ])
            res["placebo"] = plac
            lines += ["## F7. Placebo check (last test day): features swapped between stations in the same hour", "",
                      "Scores should fall to roughly the reference level; if they stayed high, something other than the station's own state would be driving them.",
                      "", md_table(plac.round(4))]
    except Exception as exc:  # noqa: BLE001 - importance is a nice-to-have
        lines += [f"_(feature importance skipped: {type(exc).__name__})_", ""]

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return res


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--db", required=True)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--horizon", type=int, default=1)
    ap.add_argument("--min-train-days", type=int, default=7)
    ap.add_argument("--n-boot", type=int, default=1000)
    ap.add_argument("--synthetic", action="store_true")
    a = ap.parse_args()
    r = evaluate(a.db, a.out, a.horizon, a.min_train_days, a.n_boot, a.synthetic)
    if r:
        print(f"wrote {a.out}")
